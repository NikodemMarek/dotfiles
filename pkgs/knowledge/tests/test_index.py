BASE = Entry(
    name="x",
    description="d",
    kind="convention",
    scope="global",
    tags=(),
    confidence="medium",
    trust="agent",
    status="active",
    created="2026-10-06",
    updated="2026-10-06",
    last_verified="2026-10-06",
    verify=None,
    related=(),
    sources=(SOURCE,),
    body="Body.",
)


def make(scope: str, name: str, description: str, **changes: object) -> Entry:
    return replace(BASE, scope=scope, name=name, description=description, **changes)


@pytest.fixture
def cfg() -> ScopesConfig:
    return parse_scopes(DEFAULT_SCOPES_TOML)


def test_scope_order():
    scopes = ["projects/a/facts", "org/acme", "topic/jj", "lang/python", "global", "lang/go"]
    assert sorted(scopes, key=scope_order) == [
        "global",
        "lang/go",
        "lang/python",
        "topic/jj",
        "org/acme",
        "projects/a/facts",
    ]


